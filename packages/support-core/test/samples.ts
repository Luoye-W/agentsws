/** 样本 → 18 §2 的 `InboundEvent`（正文按管线的规矩包了围栏）。 */
export function toInboundEvent(sample: Sample, fenced = false): InboundEvent {
  const text = fenced ? `<external_data>\n${sample.body}\n</external_data>` : sample.body
  return {
    id: `evt_${sample.id}`,
    schema_version: 1,
    workspace_id: 'ws_test',
    channel: 'email',
    kind: 'message',
    received_at: '2026-09-07T01:00:00.000Z',
    occurred_at: '2026-09-07T01:00:00.000Z',
    dedupe_key: `dk_${sample.id}`,
    actor: { external_id: sample.from },
    thread: { external_id: `thr_${sample.id}` },
    parts: [
      { type: 'text', text: `${sample.subject}\n${text}` },
      { type: 'file', ref: 'ref_1', mime: 'application/pdf', name: 'invoice.pdf' },
      { type: 'card', payload: {} },
    ],
    raw_ref: `raw_${sample.id}`,
    routing: { confidence: 1 },
    secrets_scrubbed: true,
  }
}
