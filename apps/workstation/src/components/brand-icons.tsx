type GlyphName = keyof typeof GLYPHS

/** provider / 模型卡的 id → 用哪一个标志。 */
type IconChoice =
  /** Simple Icons 里那条彩色品牌图标。 */
  | { kind: 'glyph'; glyph: GlyphName }
  /** 不属于任何一家的通用图标（`lucide` 的 `Mail`），跟着主题走。 */
  | { kind: 'lucide-mail' }
  /** 拿不到 CC0 品牌图标时的首字母圆形单色徽标。 */
  | { kind: 'letter'; letter: string }

/**
 * id 从 `apps/server/src/catalog.ts`（连接目录）与 `packages/api/src/routes/models.ts`
 * 的 `ModelProviderKind`（模型卡）来。新增一家就在这里补一条，`brand-icons.test.tsx`
 * 会照着目录逐个核对。
 */
const ICONS: Record<string, IconChoice> = {
  // ── 连接目录 ────────────────────────────────────────────────────────
  shopify_admin: { kind: 'glyph', glyph: 'shopify' },
  gmail: { kind: 'glyph', glyph: 'gmail' },
  ga4: { kind: 'glyph', glyph: 'googleanalytics' },
  gsc: { kind: 'glyph', glyph: 'googlesearchconsole' },
  meta_ads: { kind: 'glyph', glyph: 'meta' },
  // 「任意邮箱（IMAP / SMTP）」不是一家公司，给它挂任何一家的标志都是误导
  imap_smtp: { kind: 'lucide-mail' },
  // ── 模型卡（设置页）─────────────────────────────────────────────────
  deepseek: { kind: 'glyph', glyph: 'deepseek' },
  // Simple Icons 里没有 OpenAI（品牌方要求下架）；这张卡说的也是"任何 OpenAI 兼容
  // 网关"，不是 OpenAI 这家公司，所以走首字母徽标而不是去别处扒一个标志回来。
  openai_compatible: { kind: 'letter', letter: 'O' },
}

/** 这个 id 有没有专属图标（`false` = 会落到通用插头）。 */
export function hasBrandIcon(provider: string): boolean {
  return provider in ICONS
}

/**
 * 一个标识第三方服务的图标。
 *
 * @param provider 连接目录里的 `service`，或模型卡的 `kind`；认不出来落 `Plug`。
 * @param size 边长（px），默认 20。
 */
export function BrandIcon({
  provider,
  size = 20,
  className = '',
}: {
  provider: string
  size?: number
  className?: string
}): React.ReactNode {
  const choice = ICONS[provider]
  const common = {
    'data-testid': 'brand-icon',
    'data-provider': provider,
    width: size,
    height: size,
    className,
    'aria-hidden': true,
  } as const

  if (choice === undefined) {
    return <Plug {...common} data-icon="fallback" />
  }
  if (choice.kind === 'lucide-mail') {
    return <Mail {...common} data-icon="mail" />
  }
  if (choice.kind === 'letter') {
    // 单色徽标：跟着主题走（深色模式下自动变浅），不冒充任何一家的品牌色
    return (
      <svg
        {...common}
        aria-hidden
        viewBox="0 0 24 24"
        data-icon={`letter-${choice.letter.toLowerCase()}`}
      >
        <circle cx="12" cy="12" r="11" fill="none" stroke="currentColor" strokeWidth="1.6" />
        <text
          x="12"
          y="12"
          fill="currentColor"
          fontSize="12"
          fontWeight="600"
          textAnchor="middle"
          dominantBaseline="central"
        >
          {choice.letter}
        </text>
      </svg>
    )
  }

  const glyph = GLYPHS[choice.glyph]
  return (
    <svg {...common} aria-hidden viewBox="0 0 24 24" data-icon={glyph.slug}>
      {/* 品牌色写死：深浅色主题下都是官方那个色，不跟 `currentColor` 变 */}
      <path d={glyph.path} fill={glyph.hex} />
    </svg>
  )
}
