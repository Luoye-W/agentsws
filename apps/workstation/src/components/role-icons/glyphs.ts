/**
 * 角标几何（像素定，再换回 24 网格）：浅色圆底的直径 / 探出图标外框多少 / 与图标之间的缝；
 * 官网图按圆底直径的 0.72 放进去（方图的四角正好落在圆里）。
 * 16px 的左栏行里圆底 11px、官方图约 8px——再小就认不出是哪家了。
 */
export function badgeGeometry(size: number): { cx: number; r: number; cut: number; img: number } {
  const [d, out, gap] =
    size <= 14
      ? [10, 1, 1]
      : size <= 16
        ? [11, 1.5, 1]
        : size <= 20
          ? [12, 1.5, 1.25]
          : size <= 24
            ? [13, 2, 1.5]
            : [size * 0.47, 2, 1.75]
  const k = 24 / size
  const r = (d * k) / 2
  return { cx: 24 + out * k - r, r, cut: r + gap * k, img: d * k * 0.72 }
}

