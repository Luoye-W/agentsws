/**
 * WP373（Luoye 10-17，决策 976–979）：思考程度做成独立开关之后服务端那一半 + 换模型那一句。
 *
 * | 组 | 钉什么 |
 * |---|---|
 * | (a) 开 / 关型 | 官方只声明了 off 和一档（pi-ai 目录里的 `gpt-5-pro` 这类）→ `toggle`；off 也算这个模型认的档；三档那几种照 WP370 不变 |
 * | (b) 给模型那一句 | 照官方 `model-selection.ts` 原文；只在真换了模型的那句用户话后面带；没换不带；同一来源只写模型名 |
 * | (c) 事项 | AI 那段话记下是哪个模型答的（`agent_message.model`）；替身档不记 |
 *
 * 全程替身，不联网。
 */
import type { FreeChatMessageView } from '@agentsws/api'
import type { Clock, Completion, Matter, MatterEvent, ModelRef } from '@agentsws/contracts'
import type { ModelGatewayApi } from '@agentsws/model-gateway'
import type { RoleStore } from '@agentsws/roles'
import type { Work } from '@agentsws/work'
import { describe, expect, it, vi } from 'vitest'
import { modelSwitchNotice, withModelSwitchNotices } from '../src/free-chat.js'
import { hasThinkingEffort, thinkingOptionsOf } from '../src/model-thinking.js'
import { createRuntime, type RuntimeOptions } from '../src/runtime.js'

vi.setConfig({ testTimeout: 120_000 })

const clock: Clock = { now: () => '2026-10-17T10:00:00.000Z' }

describe('WP373 (a) 开 / 关型的模型', () => {
  it('只有 off 和一档 → 开关；默认开着；off 是它认的档', () => {
    const t = thinkingOptionsOf(['off', 'high'])
    expect(t).toEqual({
      options: [{ level: 'standard', effort: 'high' }],
      default: 'high',
      toggle: true,
    })
    expect(hasThinkingEffort(t, 'off')).toBe(true)
    expect(hasThinkingEffort(t, 'high')).toBe(true)
    expect(hasThinkingEffort(t, 'max')).toBe(false)
    // 那一档不在三档常用名里也一样（pi-ai 目录里有只声明 off + max 的）
    expect(thinkingOptionsOf(['off', 'max'])?.toggle).toBe(true)
    // 官方声明默认关
    expect(thinkingOptionsOf(['off', 'high'], 'off')?.default).toBe('off')
  })

  it('三档的照 WP370：没有 toggle，off 不算它认的档', () => {
    const t = thinkingOptionsOf(['off', 'low', 'high', 'max'], 'high')
    expect(t?.toggle).toBeUndefined()
    expect(t?.options.map((o) => o.level)).toEqual(['fast', 'standard', 'deep'])
    expect(hasThinkingEffort(t, 'off')).toBe(false)
  })

  it('没得选还是不出：只有 off、只有一档没有 off、空的', () => {
    expect(thinkingOptionsOf(['off'])).toBeUndefined()
    expect(thinkingOptionsOf(['high'])).toBeUndefined()
    expect(thinkingOptionsOf([])).toBeUndefined()
  })
})

const msg = (
  id: string,
  role: 'user' | 'assistant',
  model?: string,
  extra: Partial<FreeChatMessageView> = {},
): FreeChatMessageView => ({
  id,
  session_id: 's1',
  role,
  text: `${role} ${id}`,
  at: clock.now(),
  ...(model === undefined ? {} : { model: { id: model, label: model, official: false } }),
  ...extra,
})

describe('WP373 (b) 换了模型，给模型那一句（决策 978）', () => {
  it('官方原文；同一来源只写模型名，不同来源写 provider/model', () => {
    expect(modelSwitchNotice('deepseek/deepseek-flash', 'deepseek/deepseek-pro')).toBe(
      '[model changed: assistant turns above this point were generated by deepseek-flash; the session continues with deepseek-pro]',
    )
    expect(modelSwitchNotice('deepseek/deepseek-flash', 'openai-codex/gpt-5.5')).toBe(
      '[model changed: assistant turns above this point were generated by deepseek/deepseek-flash; the session continues with openai-codex/gpt-5.5]',
    )
  })

  it('这一轮换了：带在当前这句后面；没换：一句都不带', () => {
    const past = [msg('u1', 'user'), msg('a1', 'assistant', 'deepseek/flash'), msg('u2', 'user')]
    const changed = withModelSwitchNotices(past, 'openai-codex/gpt-5.5')
    expect(changed.map((x) => x.notice)).toEqual([
      undefined,
      undefined,
      modelSwitchNotice('deepseek/flash', 'openai-codex/gpt-5.5'),
    ])
    expect(
      withModelSwitchNotices(past, 'deepseek/flash').every((x) => x.notice === undefined),
    ).toBe(true)
  })

  it('以前换过的那一处每一轮都在原处（官方那句是留在会话里的）；第一句不带', () => {
    const past = [
      msg('u1', 'user'),
      msg('a1', 'assistant', 'deepseek/flash'),
      msg('u2', 'user'),
      msg('a2', 'assistant', 'openai-codex/gpt-5.5'),
      msg('u3', 'user'),
    ]
    const out = withModelSwitchNotices(past, 'openai-codex/gpt-5.5')
    expect(out.map((x) => (x.notice === undefined ? '' : x.m.id))).toEqual(['', '', 'u2', '', ''])
  })

  it('派出去的事回来报的那句（没有 model）不算换', () => {
    const past = [
      msg('u1', 'user'),
      msg('a1', 'assistant', 'deepseek/flash'),
      msg('r1', 'assistant'),
      msg('u2', 'user'),
    ]
    expect(
      withModelSwitchNotices(past, 'deepseek/flash').every((x) => x.notice === undefined),
    ).toBe(true)
  })
})

// ── (c) 事项：AI 那段话记下是哪个模型答的 ───────────────────────────

const roles = {
  // 负责人那条职责：不出政策问题卡，答一句就收（这里只看那段话记没记模型）
  effectiveConfig: () => ({
    role_id: 'common.owner',
    grounding: [],
    skills: [],
    browser_scope: [],
  }),
  assignments: { get: () => undefined },
} as unknown as RoleStore

const matter = {
  id: 'mat_1',
  schema_version: 1,
  workspace_id: 'ws_1',
  kind: 'adhoc',
  title: '店铺欢迎语',
  status: 'open',
  context: { summary: '', pinned: [], participants: [], last_activity: clock.now() },
  created_at: clock.now(),
  updated_at: clock.now(),
} as unknown as Matter

async function runOnce(mode: 'stub' | 'direct', ref: ModelRef): Promise<Partial<MatterEvent>[]> {
  const events: Partial<MatterEvent>[] = []
  const gateway = {
    async complete(req: { model?: ModelRef }) {
      return {
        text: '欢迎光临，有什么可以帮你？',
        usage: { input_tokens: 10, output_tokens: 5, cached_tokens: 0, cost_base: 0 },
        model: req.model ?? ref,
        static_prefix_hash: 'p',
      } satisfies Completion
    },
    async embed() {
      return { vectors: [], usage: { input_tokens: 0, output_tokens: 0, cached_tokens: 0 } }
    },
    usage: () => ({}),
    budget: () => ({}),
  } as unknown as ModelGatewayApi
  const runtime = createRuntime({
    workspace_id: 'ws_1',
    clock,
    random: () => 0.5,
    seed: 42,
    env: {},
    models: gateway,
    approvals: {
      create: async () => ({ id: 'apr_1', state: 'pending' }),
    } as unknown as RuntimeOptions['approvals'],
    roles,
    appendEvent: () => undefined,
    prefer: mode === 'stub' ? 'stub' : 'direct',
    modelRef: () => ref,
    hasModel: () => mode !== 'stub',
  } as RuntimeOptions)
  runtime.bind({
    appendEvent: (matter_id: string, e: Partial<MatterEvent>) => {
      events.push(e)
      return { ...e, id: `ev_${String(events.length)}`, matter_id, at: clock.now() }
    },
    onRunCompleted: () => undefined,
    onCard: () => undefined,
  } as unknown as Work)
  await runtime.startRun({
    matter,
    brief: '帮我想一句店铺欢迎语',
    actor: { person_id: 'per_1', assignment_id: 'asg_1' },
  } as Parameters<typeof runtime.startRun>[0])
  return events
}

describe('WP373 (c) 事项：AI 那段话记下是哪个模型答的', () => {
  it('direct：agent_message 带 provider/model', async () => {
    const events = await runOnce('direct', { provider: 'deepseek', model: 'deepseek-flash' })
    const said = events.filter((e) => e.kind === 'agent_message')
    expect(said.length).toBeGreaterThan(0)
    for (const e of said) expect(e.model).toBe('deepseek/deepseek-flash')
  })

  it('替身档不记', async () => {
    const events = await runOnce('stub', { provider: 'stub', model: 'stub-v1', region: 'cn' })
    for (const e of events.filter((x) => x.kind === 'agent_message'))
      expect(e.model).toBeUndefined()
  })
})
